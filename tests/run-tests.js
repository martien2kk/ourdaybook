  await service.deleteCustomCategory('音乐')
  await service.deleteCustomPrompt(travelPrompt.id)
  await service.deleteCustomCategory('旅行')
  await service.switchMockUser('A')
  let status=await service.submitEntry({dateKey:'2026-07-29',imagePath:'demo-a.jpg',caption:'A 的今天'})
  assert.strictEqual(status.unlocked,false)
  assert.strictEqual(status.partnerEntry,null,'未解锁时泄露了对方 entry')
  await assert.rejects(()=>service.unlockToday('2026-07-29'),/双方都提交/)
  await service.switchMockUser('B')
  status=await service.getTodayStatus('2026-07-29')
  assert.strictEqual(status.partnerSubmitted,true)
  assert.strictEqual(status.partnerEntry,null,'B 未提交时拿到了 A 的完整 entry')
