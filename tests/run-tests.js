  assert((await service.getPromptOverview()).categories.some(item=>item.name==='旅行'&&item.isCustom),'自定义大类创建失败')
  await assert.rejects(()=>service.addCustomPrompt({text:'本周的第二道题',category:'旅行'}),/每 7 天只能添加一道问题/,'同一周允许重复添加自定义题目')
