function shuffledQuotes(source=SHARE_QUOTES){
  const items=source.slice()
  for(let i=items.length-1;i>0;i--){
    const j=Math.floor(Math.random()*(i+1))
    const value=items[i]
    items[i]=items[j]
    items[j]=value
  }
  return items
}

